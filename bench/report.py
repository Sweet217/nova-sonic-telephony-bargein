"""Render the results table (markdown) from results/summary.json and splice it into README.md."""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"
E2E_START, E2E_END = "<!-- E2E:START -->", "<!-- E2E:END -->"


def _ms(v):
    return "–" if v is None else f"{v:,.0f}"


def _pct(v):
    return "–" if v is None else f"{100 * v:.0f}%"


def table_md(s: dict) -> str:
    lines = [
        f"_Generated by `python -m bench.run` from `results/summary.json`. Mock Nova Sonic server + simulated "
        f"PSTN line; **not** real Nova 2 Sonic numbers. n = {s['n_main_per_kind']} barge-in calls + "
        f"{s['n_main_per_kind']} caller-silent calls per row (same calls for every row; random echo delay "
        f"50–300 ms, ERL 6–30 dB, noise −65…−45 dBFS, server decision latency 150–450 ms)._",
        "",
        "| Client configuration | Stop latency p50 | Stop latency p95 | False barge-in (caller silent) | "
        "False barge-in before caller spoke | Missed true barge-in |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for name, m in s["main"].items():
        lines.append(f"| {name} | {_ms(m['stop_latency_ear_p50_ms'])} ms | {_ms(m['stop_latency_ear_p95_ms'])} ms | "
                     f"{_pct(m['false_bargein_echo_only_rate'])} | {_pct(m['false_bargein_before_onset_rate'])} | "
                     f"{_pct(m['missed_rate'])} |")
    g = s["guard_cpu_us_per_20ms_frame"]
    lines += ["",
              f"Inbound-path CPU per 20 ms frame with the echo guard (decode + guard + VAD + resample): "
              f"p50 {g['p50'] / 1000:.2f} ms, p99 {g['p99'] / 1000:.2f} ms, max {g['max'] / 1000:.2f} ms over {g['frames']:,} frames "
              f"(budget 20 ms; {s['platform']}). Median bulk-delay estimate error: "
              f"{s['delay_estimate_abs_error_ms_p50']:.1f} ms."]
    return "\n".join(lines)


def sweep_md(s: dict) -> str:
    out = ["| Sweep | Value | False barge-in, no guard | False barge-in, guard | Missed, no guard | Missed, guard |",
           "|---|---:|---:|---:|---:|---:|"]
    sw = s["sweep"]
    keys = {}
    for v in sw.values():
        keys.setdefault((v["sweep_param"], v["sweep_value"]), {})[v["config"]] = v
    for (p, val), d in keys.items():
        ng = next(v for k, v in d.items() if "no guard" in k)
        g = next(v for k, v in d.items() if "no guard" not in k)
        out.append(f"| {p} | {val:g} | {_pct(ng['false_bargein_echo_only_rate'])} | {_pct(g['false_bargein_echo_only_rate'])} | "
                   f"{_pct(ng['missed_rate'])} | {_pct(g['missed_rate'])} |")
    return "\n".join(out)


def e2e_md(e: dict) -> str:
    lines = [f"_Generated from `results/e2e_realtime.json` (`python -m bench.e2e`): {e['note']}_", "",
             "| Client configuration | Calls | Stop latency p50 | Stop latency max | Bot still talking 4 s after the caller started |",
             "|---|---:|---:|---:|---:|"]
    for name, v in e["results"].items():
        lines.append(f"| {name} | {v['n']} | {_ms(v['stop_latency_ear_p50_ms'])} ms (n={v['n_with_latency']}) | "
                     f"{_ms(v['stop_latency_ear_max_ms'])} ms | {v['n_still_talking_4s_after_onset']} of {v['n']} |")
    return "\n".join(lines)


def update_readme_e2e() -> None:
    p = ROOT / "results" / "e2e_realtime.json"
    if not p.exists():
        return
    readme = ROOT / "README.md"
    text = readme.read_text()
    block = f"{E2E_START}\n{e2e_md(json.loads(p.read_text()))}\n{E2E_END}"
    text = re.sub(re.escape(E2E_START) + ".*?" + re.escape(E2E_END), lambda _: block, text, flags=re.S)
    readme.write_text(text)


def write_table(summary: dict, out: Path) -> None:
    (out / "results_table.md").write_text(table_md(summary) + "\n\n" + sweep_md(summary) + "\n")


def update_readme(summary: dict) -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    block = f"{START}\n{table_md(summary)}\n\n<details><summary>Sweep table (n = {summary['n_sweep_per_point_per_kind']} "\
            f"per point per call type)</summary>\n\n{sweep_md(summary)}\n\n</details>\n{END}"
    text = re.sub(re.escape(START) + ".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    readme.write_text(text)


if __name__ == "__main__":
    p = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "results" / "summary.json"
    s = json.loads(p.read_text())
    update_readme(s)
    update_readme_e2e()
    print(table_md(s))
