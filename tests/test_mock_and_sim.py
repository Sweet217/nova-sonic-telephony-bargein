import numpy as np

from novabridge import nova_events as ne
from novabridge.bridge import BridgeConfig
from testbed.mock_nova import MockNovaConfig, MockNovaSonic


def utt(seconds=4.0):
    t = np.arange(int(24000 * seconds)) / 24000
    return [{"text": "one two three four", "pcm": (3000 * np.sin(2 * np.pi * 300 * t)).astype("<i2")}]


def loud_input(n=320):
    return ne.audio_input("p", "c", (0.1 * 32767 * np.sin(np.arange(n) * 0.2)).astype("<i2").tobytes())


def test_mock_streams_faster_than_real_time_and_ends_turn():
    m = MockNovaSonic(MockNovaConfig(gen_speed=2.0, first_audio_ms=250), utt(4.0))
    m.start_response(0)
    evs = [ne.parse_output(e) for _, e in m.poll(2300)]
    assert sum(e.kind == "audio" for e in evs) == 50  # 4 s / 80 ms, all generated by 250 + 2000 ms
    assert any(e.kind == "content_end" and e.type == "AUDIO" and e.stop_reason == "END_TURN" for e in evs)


def test_mock_honours_interruption_with_latency():
    cfg = MockNovaConfig(server_latency_ms=300, vad_min_ms=100, late_chunks_after_interrupt=2, gen_speed=1.0)
    m = MockNovaSonic(cfg, utt(6.0))
    m.start_response(0)
    m.poll(1000)
    for k in range(5):  # 100 ms of loud input
        m.on_input(loud_input(), 1000 + 20 * k)
    assert m.interrupts and m.interrupts[0]["t_signal"] == m.interrupts[0]["t_detect"] + 300
    out = [(t, ne.parse_output(e)) for t, e in m.poll(10_000)]
    t_sig = m.interrupts[0]["t_signal"]
    late = [e for t, e in out if e.kind == "audio" and t > t_sig]
    assert len(late) == 2  # configured late chunks
    assert any(e.kind == "interrupted" and e.type == "TEXT" for _, e in out)
    assert not any(e.kind == "audio" and t > t_sig + 1 for t, e in out)


def test_sim_end_to_end_full_mode_detects_barge_in():
    from testbed.audio import load_corpus
    from testbed.phone_line import LineConfig
    from testbed.sim import Scenario, run_scenario
    corpus = load_corpus()
    sc = Scenario("t", "barge", 3, 0, 0, 3000.0, -22.0, LineConfig(150, 15, -55), 300)
    r, _ = run_scenario(sc, BridgeConfig(mode="full", echo_guard=True), corpus)
    assert r.detected and not r.false_bargein and r.stop_latency_ear_ms < 400
    r2, _ = run_scenario(sc, BridgeConfig(mode="naive", echo_guard=False), corpus)
    assert r2.stop_latency_ear_ms is None or r2.stop_latency_ear_ms > 1000 or r2.false_bargein
